<template>
  <h1>Bài 4</h1>
  <div class="p-5">
    <h2>Tạo bài viết mới</h2>
    <input v-model="title" placeholder="Tiêu đề bài viết" />
    <input v-model="author" placeholder="Tên tác giả" />
    <textarea v-model="content" placeholder="Nội dung bài viết"></textarea>
    <button @click="submitPost">Đăng bài</button>
  </div>
</template>

<script setup>
import { ref } from 'vue'

const emit = defineEmits(['add-post'])

const title = ref('')
const content = ref('')
const author = ref('')

function submitPost() {
  if (title.value && content.value && author.value) {
    const newPost = {
      title: title.value,
      content: content.value,
      author: author.value,
      backgroundColor: '#ffffff', // có thể đổi theo style
      textColor: '#000000'
    }
    emit('add-post', newPost)

    // Reset
    title.value = ''
    content.value = ''
    author.value = ''
  }
}
</script>

<style scoped>
input,
textarea {
  display: block;
  width: 100%;
